-- 1. Create enquiries table
CREATE TABLE IF NOT EXISTS public.enquiries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT NOT NULL,
    service TEXT,
    message TEXT,
    status TEXT DEFAULT 'new',
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Set table comments
COMMENT ON TABLE public.enquiries IS 'Customer project enquiries and consultation requests from RAGAV BUILDERS website';

-- 3. Enable Row Level Security (RLS)
ALTER TABLE public.enquiries ENABLE ROW LEVEL SECURITY;

-- 4. Create Policy: Allow public / anonymous users to insert new enquiries
DROP POLICY IF EXISTS "Allow anonymous insert to enquiries" ON public.enquiries;
CREATE POLICY "Allow anonymous insert to enquiries"
    ON public.enquiries
    FOR INSERT
    TO anon, authenticated
    WITH CHECK (true);

-- 5. Create Policy: Allow authenticated users (Admins / Engineers) to view all enquiries
DROP POLICY IF EXISTS "Allow authenticated read enquiries" ON public.enquiries;
CREATE POLICY "Allow authenticated read enquiries"
    ON public.enquiries
    FOR SELECT
    TO authenticated
    USING (true);

-- 6. Create Policy: Allow authenticated users to update enquiry status (e.g., contacted, quoted)
DROP POLICY IF EXISTS "Allow authenticated update enquiries" ON public.enquiries;
CREATE POLICY "Allow authenticated update enquiries"
    ON public.enquiries
    FOR UPDATE
    TO authenticated
    USING (true)
    WITH CHECK (true);

-- 7. Grant necessary permissions to anon and authenticated roles
GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT INSERT ON TABLE public.enquiries TO anon, authenticated;
GRANT SELECT, UPDATE, DELETE ON TABLE public.enquiries TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;
